// Generates the five shared FirstRing workflows. Business logic is the bundled lib/ (tested in Node);
// the workflows are thin shells: trigger → one Code node → respond.
// Client configs are embedded at build time, so a tool call never waits on a config lookup.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export async function bundle() {
  const out = await build({
    entryPoints: [join(root, "lib/n8n-entry.mjs")],
    bundle: true, format: "iife", platform: "node", target: "node18", write: false, minify: false, legalComments: "none",
  });
  return out.outputFiles[0].text;
}

const id = (s) => createHash("sha1").update(s).digest("hex").slice(0, 8) + "-" + createHash("sha1").update(s + "x").digest("hex").slice(0, 4) + "-4000-8000-" + createHash("sha1").update(s + "y").digest("hex").slice(0, 12);

const SETTINGS = (errorWorkflowId) => ({
  executionOrder: "v1",
  saveDataSuccessExecution: "none", // successful executions hold caller data; don't keep them
  saveDataErrorExecution: "all", // needed to debug; prune with EXECUTIONS_DATA_MAX_AGE
  saveManualExecutions: false,
  ...(errorWorkflowId ? { errorWorkflow: errorWorkflowId } : {}),
});

function code(js, name, bundleSrc, clients) {
  // Clients are embedded as JSON; the bundle defines `FR`. `this.helpers` is n8n's HTTP helper.
  return [
    "// GENERATED by firstring/n8n/build.mjs — edit lib/ and regenerate, don't edit here.",
    "let FR;",
    bundleSrc,
    `const CLIENTS = ${JSON.stringify(clients)};`,
    "const ctx = FR.makeCtx({ helpers: this.helpers, env: $env, clients: CLIENTS, crypto: require('crypto') });",
    js,
  ].join("\n");
}

function webhookFlow(name, path, handler, bundleSrc, clients, errorWorkflowId) {
  const js = `const item = $input.first().json;
const out = await FR.${handler}(ctx, { headers: item.headers ?? {}, query: item.query ?? {}, body: item.body ?? {} });
return [{ json: out }];`;
  return {
    name,
    nodes: [
      { id: id(name + "wh"), name: "Webhook", type: "n8n-nodes-base.webhook", typeVersion: 2, position: [0, 0], webhookId: id(name + "hook"),
        parameters: { httpMethod: "POST", path, responseMode: "responseNode", options: {} } },
      { id: id(name + "code"), name: "FirstRing", type: "n8n-nodes-base.code", typeVersion: 2, position: [240, 0],
        parameters: { mode: "runOnceForAllItems", jsCode: code(js, name, bundleSrc, clients) } },
      { id: id(name + "resp"), name: "Respond", type: "n8n-nodes-base.respondToWebhook", typeVersion: 1.1, position: [480, 0],
        parameters: {
          respondWith: "text", responseBody: "={{ $json.body }}",
          options: { responseCode: "={{ $json.status }}", responseHeaders: { entries: [{ name: "Content-Type", value: "={{ $json.contentType }}" }] } },
        } },
    ],
    connections: { Webhook: { main: [[{ node: "FirstRing", type: "main", index: 0 }]] }, FirstRing: { main: [[{ node: "Respond", type: "main", index: 0 }]] } },
    settings: SETTINGS(errorWorkflowId),
  };
}

export async function buildWorkflows(clients, { errorWorkflowId } = {}) {
  const src = await bundle();
  const hourly = {
    name: "firstring-hourly",
    nodes: [
      { id: id("hourly-trig"), name: "Every hour at :30", type: "n8n-nodes-base.scheduleTrigger", typeVersion: 1.2, position: [0, 0],
        parameters: { rule: { interval: [{ field: "cronExpression", expression: "30 * * * *" }] } } },
      { id: id("hourly-code"), name: "FirstRing", type: "n8n-nodes-base.code", typeVersion: 2, position: [240, 0],
        parameters: { mode: "runOnceForAllItems", jsCode: code("const done = await FR.runHourly(ctx);\nreturn [{ json: { done } }];", "hourly", src, clients) } },
    ],
    connections: { "Every hour at :30": { main: [[{ node: "FirstRing", type: "main", index: 0 }]] } },
    settings: SETTINGS(errorWorkflowId),
  };
  const errors = {
    name: "firstring-errors",
    nodes: [
      { id: id("err-trig"), name: "Error Trigger", type: "n8n-nodes-base.errorTrigger", typeVersion: 1, position: [0, 0], parameters: {} },
      { id: id("err-code"), name: "FirstRing", type: "n8n-nodes-base.code", typeVersion: 2, position: [240, 0],
        parameters: { mode: "runOnceForAllItems", jsCode: code(`const e = $input.first().json;
const out = await FR.handleError(ctx, { workflow: e.workflow?.name, node: e.execution?.lastNodeExecuted, message: e.execution?.error?.message ?? e.trigger?.error?.message, executionId: e.execution?.id });
return [{ json: out }];`, "errors", src, clients) } },
    ],
    connections: { "Error Trigger": { main: [[{ node: "FirstRing", type: "main", index: 0 }]] } },
    settings: SETTINGS(null),
  };
  return [
    errors,
    webhookFlow("firstring-vapi", "firstring-vapi", "handleVapi", src, clients, errorWorkflowId),
    webhookFlow("firstring-twilio-sms", "firstring-twilio-sms", "handleTwilioSms", src, clients, errorWorkflowId),
    webhookFlow("firstring-twilio-voice", "firstring-twilio-voice", "handleTwilioVoiceFallback", src, clients, errorWorkflowId),
    hourly,
  ];
}
